import json
import logging
from pathlib import Path
from fastapi import APIRouter, HTTPException, status
from config import settings
from schemas import AnalysisRequest, AnalysisResponse, SummaryResult
from services import process_news_search

logger = logging.getLogger(__name__)

router = APIRouter(tags=["Analysis"])

# Path to static mock response
MOCK_DATA_PATH = Path(__file__).resolve().parent.parent / "data" / "mock_response.json"


@router.post("/analyze", response_model=AnalysisResponse, status_code=status.HTTP_200_OK)
async def analyze_news_bias(request: AnalysisRequest):
    """
    1. Check if MOCK_MODE is enabled; if so, return static mock JSON immediately.
    2. Otherwise, run live search with SerpAPI and fetch/clean articles.
    3. TODO: AI biasing and summarization.
    """
    query = request.search_query.strip() if request.search_query else ""
    if not query and request.text:
        query = request.text[:50].strip()

    if not query:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="A valid search_query must be provided."
        )

    # Return static mock response when MOCK_MODE=true
    if settings.MOCK_MODE:
        logger.info(f"MOCK_MODE is enabled. Returning static response from {MOCK_DATA_PATH}")
        if MOCK_DATA_PATH.exists():
            with open(MOCK_DATA_PATH, "r", encoding="utf-8") as f:
                mock_data = json.load(f)
            return AnalysisResponse(**mock_data)
        else:
            logger.warning(f"Mock file not found at {MOCK_DATA_PATH}. Falling back to live pipeline.")

    # Live pipeline: fetch news, clean content, and automatically retry if parsing fails until target_count
    articles = await process_news_search(search_query=query, target_count=request.num_articles)

    # TODO: AI Biasing & AI Summarization pipeline
    summary = SummaryResult(
        original_summary="AI Summarization pending",
        key_points=[
            f"Collected {len(articles)} news sources on '{query}'",
            "Content cleaned and extracted from article pages",
            "TODO: AI to extract key political and personal bias points"
        ],
        bias_overview="AI Biasing comparison pending"
    )

    visualization_data = {
        "status": "TODO",
        "description": "Biasing visualization (spectrum, outlets, scores) will be generated by AI"
    }

    return AnalysisResponse(
        status="success",
        query_used=query,
        articles_fetched_count=len(articles),
        articles=articles,
        summary=summary,
        visualization_data=visualization_data
    )
