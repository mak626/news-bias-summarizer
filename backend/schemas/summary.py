from typing import List, Optional
from pydantic import BaseModel, Field
from .enums import BiasGroupCategory, TopicDomain


class BiasGroup(BaseModel):
    category: BiasGroupCategory = Field(..., description="Perspective category (Left/Center/Right or Critical/Neutral/Supportive)")
    outlets: List[str] = Field(default_factory=list, description="Names of news outlets in this group")
    framing_overview: Optional[str] = Field(None, description="How outlets in this group frame the story")
    article_titles: List[str] = Field(default_factory=list, description="Titles belonging to this group")


class SummaryResult(BaseModel):
    topic_domain: TopicDomain = Field(TopicDomain.POLITICAL, description="Identified topic domain (Political, Tech/Business, General)")
    original_summary: str = Field(..., description="Neutral multi-outlet summary generated by AI")
    key_points: List[str] = Field(default_factory=list, description="Key consensus facts across all outlets")
    bias_overview: str = Field(..., description="Comparative analysis of perspectives")
    bias_groups: List[BiasGroup] = Field(default_factory=list, description="Articles and outlets grouped by perspective")
    raw_ai_markdown: Optional[str] = Field(None, description="Raw reconstructed markdown from SerpApi Google AI Mode")

